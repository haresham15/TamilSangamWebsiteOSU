export function getDailyPaadal(seedStr: string): PaadalTrack {
  let hash = 0;
  for (let i = 0; i < seedStr.length; i++) {
    hash = (hash << 5) - hash + seedStr.charCodeAt(i);
    hash |= 0;
  }
  const idx = Math.abs(hash) % PAADAL_TRACKS.length;
  return PAADAL_TRACKS[idx];
}
